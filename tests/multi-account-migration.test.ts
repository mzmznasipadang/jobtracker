import { afterEach, expect, it } from "vitest";
import { mkdtempSync, rmSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { approveEmail, claimGoogleAccount, getOwnerAccount, resetAccounts } from "@/lib/accounts";
import { openDb, resetDb, getAccountDb } from "@/lib/db";
import { encrypt, decrypt } from "@/lib/crypto";
import { getKv, setKv } from "@/lib/settings";
let dir: string;
afterEach(() => { resetDb(); resetAccounts(); if (dir)
    rmSync(dir, { recursive: true, force: true }); });
it("reopens a legacy owner database without changing schema or losing encrypted Gmail data", () => {
    resetDb();
    resetAccounts();
    dir = mkdtempSync(join(tmpdir(), "jt-migration-"));
    process.env.DB_PATH = join(dir, "jobtracker.db");
    const legacy = openDb(process.env.DB_PATH);
    const token = encrypt("legacy-refresh-token");
    legacy.prepare("INSERT INTO kv VALUES ('gmailToken',?)").run(JSON.stringify(token));
    legacy.prepare("INSERT INTO kv VALUES ('masterCv',?)").run(JSON.stringify({ legacy: "cv-data" }));
    legacy.prepare("INSERT INTO jobs (url,source,company,title) VALUES ('u','other','Existing','Role')").run();
    legacy.close();
    const owner = getOwnerAccount();
    claimGoogleAccount({ email: owner.email, sub: "owner-sub", emailVerified: true });
    approveEmail("member@gmail.com");
    const member = claimGoogleAccount({ email: "member@gmail.com", sub: "member-sub", emailVerified: true });
    setKv(member, "masterCv", { member: "private" });
    resetDb();
    resetAccounts();
    expect(getOwnerAccount().id).toBe(owner.id);
    expect(decrypt(getKv<string>(owner, "gmailToken")!)).toBe("legacy-refresh-token");
    expect(getKv(owner, "masterCv")).toEqual({ legacy: "cv-data" });
    expect(getKv(member, "masterCv")).toEqual({ member: "private" });
    expect(getAccountDb(member).prepare("SELECT * FROM jobs").all()).toEqual([]);
    resetDb();
    const oldApp = openDb(process.env.DB_PATH!);
    expect(oldApp.pragma("user_version", { simple: true })).toBe(3);
    expect(oldApp.prepare("SELECT company FROM jobs").get()).toEqual({ company: "Existing" });
    oldApp.close();
});
